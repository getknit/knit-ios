/// The colors a face without a photo wears: the disc, and the initial on it (`AvatarTint.kt` in knit-next, its ADR
/// 2026-09.j8c7). Each is a container and on-container pair at Material's own tones, disc 85 and letter 10 in light,
/// disc 30 and letter 90 in dark, so the initial clears 4.5:1 by construction, which `FaceTests` measures.
///
/// The key is a person's node id, or a group's id, never a name: it survives a rename, every phone that knows the
/// person derives the same one, and so Ada is the same green in your list and on Bob's phone, Android's included.
/// Twelve slots means one person in twelve shares a color, so a tint is a cue and never a fingerprint; the safety
/// number is what tells people apart. Android nudges the palette toward the wallpaper under Material You, and uses
/// these tables verbatim otherwise, which is what the iPhone always does.
public struct AvatarTint: Sendable, Equatable {
    /// The disc, as `0xRRGGBB`.
    public let container: Int
    /// The initial on it, as `0xRRGGBB`.
    public let onContainer: Int

    /// The pair `container` and `onContainer`.
    public init(container: Int, onContainer: Int) {
        self.container = container
        self.onContainer = onContainer
    }

    /// The light palette: twelve hues 30° apart in HCT, generated by knit-next's `scripts/gen-avatar-palette.py` with
    /// the disc at tone 85 and chroma 20, and the initial at tone 10.
    public static let light = Light.all.map { Self(container: $0.container, onContainer: $0.onContainer) }

    /// The dark palette, slot for slot the same hues as ``light``: the disc at tone 30 and chroma 28, the initial at
    /// tone 90.
    public static let dark = Dark.all.map { Self(container: $0.container, onContainer: $0.onContainer) }

    /// ``light``, by hue.
    private enum Light {
        static let hue0 = (container: 0xF8C8D5, onContainer: 0x2E131C)
        static let hue30 = (container: 0xFDC8BD, onContainer: 0x30130E)
        static let hue60 = (container: 0xF8CCAA, onContainer: 0x2C1602)
        static let hue90 = (container: 0xE7D2A3, onContainer: 0x241A00)
        static let hue120 = (container: 0xD2D8AD, onContainer: 0x191E03)
        static let hue150 = (container: 0xC1DCBE, onContainer: 0x0A200E)
        static let hue180 = (container: 0xB7DCD1, onContainer: 0x00211A)
        static let hue210 = (container: 0xB7DBE1, onContainer: 0x002025)
        static let hue240 = (container: 0xBFD8EC, onContainer: 0x031E2D)
        static let hue270 = (container: 0xCBD4F2, onContainer: 0x121B31)
        static let hue300 = (container: 0xDBCFF0, onContainer: 0x1F1730)
        static let hue330 = (container: 0xEBCBE7, onContainer: 0x281428)
        static let all = [hue0, hue30, hue60, hue90, hue120, hue150, hue180, hue210, hue240, hue270, hue300, hue330]
    }

    /// ``dark``, by hue.
    private enum Dark {
        static let hue0 = (container: 0x683848, onContainer: 0xFFD9E2)
        static let hue30 = (container: 0x6B392F, onContainer: 0xFFDAD3)
        static let hue60 = (container: 0x653E18, onContainer: 0xFFDCC1)
        static let hue90 = (container: 0x57440F, onContainer: 0xFCE09B)
        static let hue120 = (container: 0x434B1B, onContainer: 0xDEE8A9)
        static let hue150 = (container: 0x2B4E2F, onContainer: 0xC4EDC3)
        static let hue180 = (container: 0x135044, onContainer: 0xB4EEDF)
        static let hue210 = (container: 0x0D4E57, onContainer: 0xB3ECF6)
        static let hue240 = (container: 0x214B64, onContainer: 0xC8E6FF)
        static let hue270 = (container: 0x38466B, onContainer: 0xDAE2FF)
        static let hue300 = (container: 0x4C4069, onContainer: 0xE9DDFF)
        static let hue330 = (container: 0x5D3B5D, onContainer: 0xFFD6FB)
        static let all = [hue0, hue30, hue60, hue90, hue120, hue150, hue180, hue210, hue240, hue270, hue300, hue330]
    }

    /// The slot `key` wears (`avatarTintIndex`): Java's `String.hashCode`, the polynomial over UTF-16 code units the
    /// Java spec fixes, floor-modded by the palette's size, since the hash is signed. A node id is base32 of a SHA-256,
    /// so its low bits spread evenly. The slot is the contract between phones: a "better" hash or a resized palette
    /// would recolor everyone, on one platform only.
    public static func slot(for key: String) -> Int {
        var hash: Int32 = 0
        for unit in key.utf16 {
            hash = hash &* javaHashMultiplier &+ Int32(unit)
        }
        let count = Int32(light.count)
        return Int(((hash % count) + count) % count)
    }

    /// The multiplier in Java's `String.hashCode`.
    private static let javaHashMultiplier: Int32 = 31
}
